import type { ArtifactStore, EventStore, RepoRecord } from '@gatehouse/core';
import { verifyDecision, type ApproverStore, type WebAuthnOrigin } from '@gatehouse/gates';
import { parseGitHubRemote, type GitHubClient } from '@gatehouse/github';
import { git } from '@gatehouse/targets';
import { MARKER } from '@gatehouse/workflows';

export interface BranchPackage {
  runId: string;
  repo: string;
  base: string;
  head: string;
  branch: string;
  title?: string;
  ticket?: string;
  artifacts: Record<string, string>;
  warnings: string[];
}

export type BranchPublishOutcome =
  | { status: 'published'; url: string; number: number }
  | { status: 'already-published'; url: string }
  | { status: 'rejected-by-human' }
  | { status: 'refused'; reason: string };

/**
 * Publisher for pipelines that produce code (ticket, legacy tests). The only path from an agent's
 * work to GitHub: re-verify the signed final-gate decision for this exact package, push the
 * reviewed commit to a gatehouse/* branch (never the default branch), and open a draft PR.
 * The token travels in git's environment-based config, not on the command line.
 */
export async function publishBranch(deps: {
  events: EventStore;
  artifacts: ArtifactStore;
  approvers: ApproverStore;
  github: GitHubClient;
  token: string;
  repo: RepoRecord;
  web: WebAuthnOrigin;
  runId: string;
}): Promise<BranchPublishOutcome> {
  const { events, runId } = deps;
  const check = await verifyDecision(events, deps.approvers, runId, deps.web);
  if (!check.ok) {
    events.append(runId, 'PUBLISH_REFUSED', { reason: check.reason });
    return { status: 'refused', reason: check.reason };
  }
  if (check.decision.decision !== 'approve') return { status: 'rejected-by-human' };

  const pkg = JSON.parse(deps.artifacts.read(check.decision.artifact).toString('utf8')) as BranchPackage;
  const gh = parseGitHubRemote(deps.repo.source);
  if (!gh) return { status: 'refused', reason: 'repo source is not a GitHub URL' };
  if (!pkg.branch.startsWith('gatehouse/') || pkg.branch === deps.repo.defaultBranch) return { status: 'refused', reason: `refusing to push to ${pkg.branch}` };

  const existing = await deps.github.findPullByHead(gh.owner, gh.repo, pkg.branch);
  if (existing) {
    events.append(runId, 'PUBLISH_SKIPPED', { reason: 'pull request already exists', url: existing.url });
    return { status: 'already-published', url: existing.url };
  }

  const ref = `refs/gatehouse/runs/${runId}`;
  const sha = await git(['-C', deps.repo.mirror, 'rev-parse', ref]);
  if (sha !== pkg.head) return { status: 'refused', reason: `the approved head ${pkg.head.slice(0, 10)} does not match ${ref} (${sha.slice(0, 10)})` };
  const basic = Buffer.from(`x-access-token:${deps.token}`).toString('base64');
  await git(['-C', deps.repo.mirror, 'push', `https://github.com/${gh.owner}/${gh.repo}.git`, `${pkg.head}:refs/heads/${pkg.branch}`], {
    env: {
      ...process.env,
      GIT_TERMINAL_PROMPT: '0',
      GIT_CONFIG_COUNT: '1',
      GIT_CONFIG_KEY_0: 'http.https://github.com/.extraheader',
      GIT_CONFIG_VALUE_0: `AUTHORIZATION: basic ${basic}`,
    },
    timeoutMs: 10 * 60_000,
  });
  events.append(runId, 'BRANCH_PUSHED', { branch: pkg.branch, head: pkg.head });

  const summary = pkg.artifacts.summary ? deps.artifacts.read(pkg.artifacts.summary).toString('utf8') : '';
  const body = [
    summary,
    '',
    '---',
    `Generated by Gatehouse run \`${runId}\`; package \`${check.decision.artifact.slice(0, 16)}\` approved by passkey \`${check.decision.credentialId.slice(0, 12)}…\`${check.decision.reason ? ` ("${check.decision.reason}")` : ''}.`,
    'Draft: requires review by a CODEOWNER other than the person who started this run before merge.',
    marker(runId),
  ].join('\n');
  const title = pkg.ticket ? `${pkg.ticket}: ${pkg.title ?? ''}`.trim() : `Characterization tests (${pkg.branch.replace('gatehouse/', '')})`;
  const pr = await deps.github.createPull(gh.owner, gh.repo, { title, head: pkg.branch, base: deps.repo.defaultBranch, body, draft: true });
  events.append(runId, 'PUBLISHED', { url: pr.url, number: pr.number, branch: pkg.branch });
  return { status: 'published', url: pr.url, number: pr.number };
}

const marker = (runId: string) => MARKER(runId);
