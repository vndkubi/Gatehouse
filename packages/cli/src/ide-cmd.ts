import { existsSync, mkdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { compileAgents, compileIde, listAgents, loadAgent, type CompileTarget } from '@gatehouse/workflows';

const out = (s = '') => process.stdout.write(`${s}\n`);
const BIN = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..', '..', 'bin', 'gatehouse.mjs');
const TARGETS: CompileTarget[] = ['copilot', 'codex', 'claude'];

function targetsFrom(flag: string | boolean | undefined): CompileTarget[] {
  if (typeof flag !== 'string' || flag === 'all') return TARGETS;
  const list = flag.split(',').map((s) => s.trim()) as CompileTarget[];
  const bad = list.filter((t) => !TARGETS.includes(t));
  if (bad.length) throw new Error(`unknown target ${bad.join(', ')} (use ${TARGETS.join(', ')} or all)`);
  return list;
}

/** Writes generated files; never overwrites a file Gatehouse did not generate unless --force. */
function writeFiles(root: string, files: Record<string, string>, force: boolean): { written: string[]; skipped: string[] } {
  const written: string[] = [];
  const skipped: string[] = [];
  for (const [rel, text] of Object.entries(files)) {
    const file = join(root, rel);
    if (existsSync(file) && !force && !readFileSync(file, 'utf8').includes('Generated by `gatehouse') && !rel.startsWith('.gatehouse/')) {
      skipped.push(rel);
      continue;
    }
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(file, text);
    written.push(rel);
  }
  return { written, skipped };
}

export function agentsListCmd(json: boolean): number {
  const specs = listAgents().map(loadAgent);
  if (json) {
    out(JSON.stringify(specs.map((s) => ({ ...s.meta, version: s.version })), null, 2));
    return 0;
  }
  for (const s of specs) out(`${s.name.padEnd(24)} ${s.version}  ${s.meta.executor.padEnd(8)} ${s.meta.tier.padEnd(15)} ${s.meta.scope.padEnd(10)} ${s.meta.role}`);
  return 0;
}

/** Compiles the neutral Agent Specs into each executor's format under --out (default ./gatehouse-agents). */
export function agentsCompileCmd(flags: Record<string, string | boolean>): number {
  const outDir = resolve(typeof flags.out === 'string' ? flags.out : 'gatehouse-agents');
  const files = compileAgents(targetsFrom(flags.for));
  const { written, skipped } = writeFiles(outDir, files, Boolean(flags.force));
  out(`Compiled ${written.length} file(s) into ${outDir}`);
  for (const s of skipped) out(`  skipped ${s} (exists and was not generated by Gatehouse; --force to overwrite)`);
  return 0;
}

/** Installs slash commands, the Gatehouse agent and the MCP server registration into a repo checkout. */
export function ideInstallCmd(flags: Record<string, string | boolean>): number {
  const target = resolve(typeof flags.target === 'string' ? flags.target : '.');
  if (!existsSync(target) || !statSync(target).isDirectory()) throw new Error(`${target} is not a directory`);
  const { files, json, notes } = compileIde({ mcpCommand: [process.execPath, BIN, 'mcp', 'serve'], targets: targetsFrom(flags.for) });
  const { written, skipped } = writeFiles(target, files, Boolean(flags.force));
  for (const [rel, merge] of Object.entries(json)) {
    const file = join(target, rel);
    let current: Record<string, unknown> = {};
    if (existsSync(file)) {
      try {
        current = JSON.parse(readFileSync(file, 'utf8')) as Record<string, unknown>;
      } catch {
        skipped.push(`${rel} (not plain JSON; add the gatehouse server by hand: ${JSON.stringify(merge({}))})`);
        continue;
      }
    }
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(file, `${JSON.stringify(merge(current), null, 2)}\n`);
    written.push(rel);
  }
  out(`Installed into ${target}:`);
  for (const w of written.sort()) out(`  ${w}`);
  for (const s of skipped) out(`  skipped ${s}`);
  for (const n of notes) out(n);
  out('');
  out('The IDE tools talk to the console: keep `gatehouse serve` running. Approvals stay in the console (passkey).');
  out('Gatehouse masks these files inside its own workspaces, so they never steer Gatehouse agents.');
  return 0;
}
